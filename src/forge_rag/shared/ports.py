from typing import Any, Protocol

from forge_rag.shared.models import DocumentInput, Generated, Hit, Piece, Principal, Section


class Embedder(Protocol):
    signature: str
    dimensions: int

    def embed(self, texts: list[str]) -> list[list[float]]: ...


class Generator(Protocol):
    def generate(self, question: str, hits: list[Hit]) -> Generated: ...


class Extractor(Protocol):
    def extract(self, content: str, media_type: str) -> list[Section]: ...


class Chunker(Protocol):
    signature: str

    def split(self, sections: list[Section]) -> list[Piece]: ...


class Reranker(Protocol):
    def rank(self, question: str, hits: list[Hit]) -> list[Hit]: ...


class Repository(Protocol):
    def enqueue(
        self, principal: Principal, request: DocumentInput, key: str, signature: str
    ) -> dict[str, Any]: ...
    def document(self, principal: Principal, document_id: str) -> dict[str, Any]: ...
    def job(self, principal: Principal, job_id: str) -> dict[str, Any]: ...
    def claim(self, lease_seconds: int) -> dict[str, Any] | None: ...
    def renew(self, job: dict[str, Any], lease_seconds: int) -> bool: ...
    def publish(
        self, job: dict[str, Any], pieces: list[Piece], vectors: list[list[float]]
    ) -> bool: ...
    def fail(self, job: dict[str, Any], code: str, permanent: bool, max_attempts: int) -> None: ...
    def delete(self, principal: Principal, document_id: str) -> None: ...
    def search(
        self,
        principal: Principal,
        dataset: str,
        signature: str,
        vector: list[float],
        question: str,
        limit: int,
    ) -> list[Hit]: ...
    def still_allowed(self, principal: Principal, ids: list[str]) -> bool: ...
    def ready(self) -> bool: ...
    def close(self) -> None: ...
